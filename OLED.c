static const char *TAG = "OLED_DRIVER";

// 新版API：总线句柄、OLED设备句柄
static i2c_master_bus_handle_t oled_bus_handle;
static i2c_master_dev_handle_t oled_dev_handle;

/**
 * @brief 新版官方API：I2C总线初始化（严格对标文档流程）
 */
static void oled_i2c_bus_init(void)
{
    // 1. 新版总线配置结构体
    i2c_master_bus_config_t bus_conf = {
        .i2c_port = I2C_NUM_0,
        .sda_io_num = OLED_I2C_SDA_PIN,
        .scl_io_num = OLED_I2C_SCL_PIN,
        .glitch_ignore_cnt = 7,
        .clk_source = I2C_CLK_SRC_DEFAULT,
    };

    // 2. 官方API：创建I2C主机总线，获取总线句柄（你之前缺失的核心步骤）
    ESP_ERROR_CHECK(i2c_new_master_bus(&bus_conf, &oled_bus_handle));

    // 3. 配置OLED从机设备参数
    i2c_device_config_t dev_conf = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = OLED_ADDR,    // OLED真实I2C地址
        .scl_speed_hz = OLED_I2C_FREQ,
    };

    // 4. 官方API：把OLED设备挂载到总线上，获取设备通信句柄
    ESP_ERROR_CHECK(i2c_master_bus_add_device(oled_bus_handle, &dev_conf, &oled_dev_handle));
}

/**
 * @brief 新版官方API：I2C发送数据（完全替代旧版i2c_master_write_to_device）
 */
static esp_err_t oled_i2c_transmit(uint8_t reg, uint8_t data)
{
    uint8_t tx_buf[2] = {reg, data};
    // 官方新版传输函数，超时50ms
    return i2c_master_transmit(oled_dev_handle, tx_buf, sizeof(tx_buf), pdMS_TO_TICKS(50));
}

// 底层：向OLED写命令
static void oled_write_cmd(uint8_t cmd)
{
    ESP_ERROR_CHECK(oled_i2c_transmit(OLED_CMD, cmd));
}

// 底层：向OLED写显示数据
static void oled_write_data(uint8_t data)
{
    ESP_ERROR_CHECK(oled_i2c_transmit(OLED_DATA, data));
}

/**
 * @brief OLED整体初始化（总线+屏幕初始化）
 */
void OLED_Init(void)
{
    // 第一步：新版I2C总线初始化
    oled_i2c_bus_init();
    vTaskDelay(pdMS_TO_TICKS(100));

    // SSD1306 128*32 标准初始化指令（完全不变）
    oled_write_cmd(0xAE);    // 关闭显示
    oled_write_cmd(0xD5);    // 时钟分频
    oled_write_cmd(0x80);    
    oled_write_cmd(0xA8);    // 驱动路数
    oled_write_cmd(0x1F);    // 128*32专用参数
    oled_write_cmd(0xD3);    // 显示偏移
    oled_write_cmd(0x00);    
    oled_write_cmd(0x40);    // 显示起始行
    oled_write_cmd(0x8D);    // 电荷泵开启
    oled_write_cmd(0x14);    
    oled_write_cmd(0x20);    // 内存寻址模式
    oled_write_cmd(0x00);    
    oled_write_cmd(0xA1);    // 段映射
    oled_write_cmd(0xC8);    // COM扫描方向
    oled_write_cmd(0xDA);    // COM引脚配置
    oled_write_cmd(0x02);    
    oled_write_cmd(0x81);    // 对比度
    oled_write_cmd(0xCF);
    oled_write_cmd(0xD9);    // 预充电周期
    oled_write_cmd(0xF1);
    oled_write_cmd(0xDB);    // VCOM电平
    oled_write_cmd(0x30);
    oled_write_cmd(0xA4);    
    oled_write_cmd(0xA6);    // 正常显示
    oled_write_cmd(0xAF);    // 开启屏幕显示

    OLED_Clear();
    ESP_LOGI(TAG, "OLED新版驱动初始化完成");
}

/**
 * @brief OLED清屏
 */
void OLED_Clear(void)
{
    uint8_t page, col;
    for(page = 0; page < 4; page++)
    {
        oled_write_cmd(0xB0 + page);
        oled_write_cmd(0x00);
        oled_write_cmd(0x10);
        for(col = 0; col < 128; col++)
        {
            oled_write_data(0x00);
        }
    }
}

/**
 * @brief 显示单个ASCII字符（适配你的asc2_0806字模）
 */
static void OLED_ShowChar(uint8_t x, uint8_t y, uint8_t chr)
{
    uint8_t c = chr - ' ';
    uint8_t i;

    oled_write_cmd(0xB0 + y);
    oled_write_cmd(0x00 | (x&0x0F));
    oled_write_cmd(0x10 | (x>>4));

    for(i=0; i<6; i++)
    {
        oled_write_data(asc2_0806[c][i]);
    }
}

/**
 * @brief 显示字符串
 */
void OLED_ShowString(uint8_t x, uint8_t y, char *str)
{
    while(*str)
    {
        OLED_ShowChar(x, y, *str);
        x += 6;
        if(x > 127)
        {
            x = 0;
            y++;
        }
        str++;
    }
}

/**
 * @brief 显示数字
 */
void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    uint8_t i;
    for(i=0; i<len; i++)
    {
        uint32_t pow_num = 1;
        for(uint8_t j=0; j<len-i-1; j++) pow_num *= 10;
        
        uint8_t t = (num / pow_num) % 10;
        OLED_ShowChar(x, y, t + '0');
        x += 6;
    }
}